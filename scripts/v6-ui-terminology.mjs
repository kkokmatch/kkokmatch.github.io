import fs from 'node:fs';
const file='app-v6.0.js';
let src=fs.readFileSync(file,'utf8');
if(!src.includes("window.__kokmatchStandalone='6.0'"))throw new Error('Not a v6 standalone runtime');
const terms=[['총관리자','개발자'],['모임관리자','모임장'],['게임편성자','운영진'],['일반회원','일반']];
for(const [from,to] of terms)src=src.replaceAll(from,to);
const runtimeMap="({'총관리자':'개발자','모임관리자':'모임장','게임편성자':'운영진','일반회원':'일반'}[String(VALUE||'')]||VALUE)";
src=src.replace("esc(x.roleLabel||'PIN')",`esc(${runtimeMap.replaceAll('VALUE',"x.roleLabel||'PIN'")})`);
src=src.replaceAll('esc(c.roleLabel)',`esc(${runtimeMap.replaceAll('VALUE','c.roleLabel')})`);
src=src.replace("escV6(x.roleLabel||'')","escV6(x.role==='admin'?'개발자':x.role==='manager'?'모임장':x.role==='organizer'?'운영진':x.role==='member'?'일반':"+runtimeMap.replaceAll('VALUE',"x.roleLabel||''")+")");
fs.writeFileSync(file,src);
console.log('Canonical v6 role terminology applied: 개발자 / 모임장 / 운영진 / 일반');
